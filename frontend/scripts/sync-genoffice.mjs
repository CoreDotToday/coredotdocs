// third_party/genoffice-docx(Apache-2.0, 그대로 복사한 GenOffice 코드)의 소스를 frontend/vendor/genoffice-docx/로 복사한다.
// Next.js(Turbopack)는 프로젝트 밖의 파일을 번들하지 않으므로 빌드 때 안으로 가져오며, 진실은 third_party/ 쪽이다 (vendor/는 git 무시).
// dev·build 전에 실행된다. 바뀐 파일만 다시 쓴다.
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";

const SRC = path.resolve(process.cwd(), "..", "third_party", "genoffice-docx");
const OUT = path.resolve(process.cwd(), "vendor", "genoffice-docx");
// 번들에 들어갈 것만: 각 패키지의 src (tests·scripts 제외), 편집기 렌더러
const PARTS = ["packages/docx-engine/src", "packages/zip-gate/src", "packages/agent-core/src", "packages/pptx-engine/src", "packages/pptx-render/src", "packages/font-metrics", "packages/i18n/src", "packages/ui/src", "shims", "apps/docs/src/renderer"];

function copyTree(from, to) {
  let n = 0;
  mkdirSync(to, { recursive: true });
  for (const name of readdirSync(from)) {
    if (name === "node_modules" || name === "tests" || name === "scripts") continue;
    const s = path.join(from, name);
    const d = path.join(to, name);
    if (statSync(s).isDirectory()) {
      n += copyTree(s, d);
      continue;
    }
    const data = readFileSync(s);
    if (existsSync(d) && Buffer.compare(readFileSync(d), data) === 0) continue;
    writeFileSync(d, data);
    n += 1;
  }
  return n;
}

if (!existsSync(SRC)) {
  console.error(`third_party/genoffice-docx가 없습니다: ${SRC}`);
  process.exit(1);
}
let written = 0;
for (const part of PARTS) {
  const from = path.join(SRC, part);
  if (!existsSync(from)) continue;
  written += copyTree(from, path.join(OUT, part));
}
for (const name of ["LICENSE", "NOTICE", "NOTICE-upstream"]) cpSync(path.join(SRC, name), path.join(OUT, name));
written += await scopeEditorCss();
console.log(`genoffice-docx → vendor/genoffice-docx/ (${written}개 파일 갱신)`);
void rmSync;

/**
 * 편집기 스타일(styles.css, 1.4만 줄)은 :root·body·button 같은 전역 규칙을 담고 있어 그대로 넣으면 우리 셸의 모양을 바꾼다.
 * 모든 선택자를 `.cdd-docx` 아래로 좁힌 사본(styles.scoped.css)을 만든다 — :root/html/body는 `.cdd-docx` 자신으로.
 */
async function scopeEditorCss() {
  const src = path.join(OUT, "apps", "docs", "src", "renderer", "styles.css");
  const dst = path.join(OUT, "apps", "docs", "src", "renderer", "styles.scoped.css");
  if (!existsSync(src)) return 0;
  const { default: postcss } = await import("postcss");
  const { default: prefixer } = await import("postcss-prefix-selector");
  // 편집기 CSS는 @genoffice/ui/tokens.css의 기본 토큰(--text·--border·--surface…)을 전제한다: 앞에 붙여 같이 좁힌다
  const tokens = path.join(OUT, "packages", "ui", "src", "tokens.css");
  const css = (existsSync(tokens) ? readFileSync(tokens, "utf8") + "\n" : "") + readFileSync(src, "utf8");
  const out = await postcss([
    prefixer({
      prefix: ".cdd-docx",
      transform(prefix, selector, prefixed) {
        const s = selector.trim();
        if (s === ":root" || s === "html" || s === "body" || s === "html, body") return prefix;
        if (/^(:root|html|body)\b/.test(s)) return s.replace(/^(:root|html|body)/, prefix);
        if (s === "*" || s.startsWith("*,")) return `${prefix} ${s}`;
        return prefixed;
      },
    }),
  ]).process(css, { from: src, to: dst });
  const banner = "/* generated by frontend/scripts/sync-genoffice.mjs from third_party/genoffice-docx/apps/docs/src/renderer/styles.css (Apache-2.0): every selector scoped under .cdd-docx */\n";
  const next = banner + out.css;
  if (existsSync(dst) && readFileSync(dst, "utf8") === next) return 0;
  writeFileSync(dst, next);
  return 1;
}
